final RegExp _cyrillic = RegExp(r'[а-яА-ЯёЁ]');

/// Put on every hardcoded UI string in the app (`Text('save'.tr)`,
/// `hintText: 'list name…'.tr`, etc.) so it renders in whichever
/// language `LocaleService.appIsRussian` currently says — the same
/// single Settings toggle that already chose title/poster language.
///
/// Most of the app is written source-English, translated via [AppTranslations.ru].
/// A few screens were originally written source-Russian; for those this
/// looks the other way through [AppTranslations.en]. Either way, a string
/// with no entry yet just passes through unchanged rather than breaking.
extension TrString on String {
  String get tr {
    final wantRussian = LocaleService.appIsRussian;
    final isRussianSource = _cyrillic.hasMatch(this);
    if (wantRussian) {
      if (isRussianSource) return this;
      return AppTranslations.ru[this] ?? this;
    } else {
      if (!isRussianSource) return this;
      return AppTranslations.en[this] ?? this;
    }
  }
}
